// Writes docs/img/guilloche.svg: the security-paper linework behind the promo
// page's passport pages. Seamless horizontal tile of phase-shifted waves, the
// way banknote and passport guilloche bands are drawn. Run: node design/make-guilloche.js
const fs = require('fs');
const path = require('path');

const W = 480;
const H = 240;
const lines = [];
for (let k = 0; k < 18; k += 1) {
  const pts = [];
  for (let x = 0; x <= W; x += 4) {
    const t = (x / W) * Math.PI * 2;
    // Two waves per tile width so the tile repeats seamlessly; the second
    // harmonic and the phase per line make the woven look.
    const y = H / 2
      + 70 * Math.sin(2 * t + k * 0.35)
      + 18 * Math.sin(6 * t - k * 0.5)
      + (k - 8.5) * 5;
    pts.push(`${x},${y.toFixed(1)}`);
  }
  lines.push(`<polyline points="${pts.join(' ')}"/>`);
}
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">
<!-- Generated by design/make-guilloche.js for the Budget Planner promo page -->
<g fill="none" stroke="#6E8F7A" stroke-width="0.6" stroke-opacity="0.32">${lines.join('')}</g>
</svg>
`;
fs.writeFileSync(path.join(__dirname, '..', 'docs', 'img', 'guilloche.svg'), svg);
console.log('wrote docs/img/guilloche.svg');
